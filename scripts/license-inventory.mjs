// Regenerates docs/DEPENDENCY-INVENTORY.md from installed package metadata.
// Run: node scripts/license-inventory.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = process.cwd()
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const rows = (section) =>
  Object.keys(pkg[section] ?? {}).sort().map((name) => {
    const m = JSON.parse(readFileSync(join(root, 'node_modules', name, 'package.json'), 'utf8'))
    const lic = typeof m.license === 'string' ? m.license : m.license?.type ?? (m.licenses ? m.licenses.map((l) => l.type).join(' OR ') : 'UNKNOWN')
    return `| ${name} | ${m.version} | ${lic} |`
  })

const out = `# Dependency inventory (generated)

Generated by \`scripts/license-inventory.mjs\` from installed package metadata. This is an **engineering inventory, not legal advice**.
The current proposed project license is **MIT** (see the root \`LICENSE\` file); the repository owner should review it before public release.

## Runtime dependencies (npm)
| Package | Version | License |
|---|---|---|
${rows('dependencies').join('\n')}

## Development dependencies (npm)
| Package | Version | License |
|---|---|---|
${rows('devDependencies').join('\n')}

## Bundled fonts
Manrope and Cairo are bundled through \`@fontsource/*\` (SIL Open Font License 1.1). The OFL text and attribution must ship with the app before release.

## Windows runtime tools
The Windows release workflow downloads yt-dlp and an FFmpeg LGPL shared build, copies the Node.js runtime provisioned by actions/setup-node, verifies the yt-dlp SHA-256 checksum and records the exact tool versions in \`resources/tools/win32-x64/tool-versions.json\`. Tool licenses and upstream notices are shipped alongside the generated packages. Verify upstream license terms and attribution before each public release.
`
writeFileSync(join(root, 'docs', 'DEPENDENCY-INVENTORY.md'), out)
console.log('Wrote docs/DEPENDENCY-INVENTORY.md')
